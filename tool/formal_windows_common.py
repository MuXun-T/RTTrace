def load_module_from_path(module_path: Path, module_name: str, repo_root: Path) -> Any:
    repo_text = str(repo_root)
    if repo_text not in sys.path:
        sys.path.insert(0, repo_text)
    spec = importlib.util.spec_from_file_location(module_name, module_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"failed to load module spec: {module_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_patched_main(
    *,
    module_path: Path,
    module_name: str,
    patcher: Callable[[Any], None],
    stdout_path: Path,
    stderr_path: Path,
    time_path: Path,
    repo_root: Path,
) -> None:
    module = load_module_from_path(module_path, module_name, repo_root)
    patcher(module)
    ensure_parent(stdout_path)
    ensure_parent(stderr_path)
    ensure_parent(time_path)
    started = time.perf_counter()
    old_stdout = sys.stdout
    old_stderr = sys.stderr
    exit_code = 0
    with stdout_path.open("w", encoding="utf-8") as stdout_handle, stderr_path.open(
        "w",
        encoding="utf-8",
    ) as stderr_handle:
        sys.stdout = Tee(old_stdout, stdout_handle)
        sys.stderr = Tee(old_stderr, stderr_handle)
        try:
            result = module.main()
            if isinstance(result, int):
                exit_code = result
        except SystemExit as exc:
            exit_code = int(exc.code) if isinstance(exc.code, int) else 1
            if exit_code:
                traceback.print_exc()
        except Exception:
            exit_code = 1
            traceback.print_exc()
        finally:
            sys.stdout = old_stdout
            sys.stderr = old_stderr
    elapsed = round(time.perf_counter() - started, 6)
    time_path.write_text(f"{elapsed:.6f}\n", encoding="utf-8")
    if exit_code:
        raise RuntimeError(f"runner failed: {module_path.name} exit_code={exit_code}")


def flatten_field_paths(payload: Any, prefix: str = "") -> set[str]:
    if isinstance(payload, dict):
        paths: set[str] = set()
        for key, value in payload.items():
            next_prefix = f"{prefix}.{key}" if prefix else str(key)
            paths.add(next_prefix)
            paths.update(flatten_field_paths(value, next_prefix))
        return paths
    if isinstance(payload, list):
        paths: set[str] = set()
        list_prefix = f"{prefix}[]" if prefix else "[]"
        paths.add(list_prefix)
        for item in payload:
            paths.update(flatten_field_paths(item, list_prefix))
        return paths
    return set()


