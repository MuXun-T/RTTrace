def _first_nonempty_string(*values: Any) -> str | None:
    for value in values:
        if value is None:
            continue
        text = str(value).strip()
        if text:
            return text
    return None


def _first_present_value(*values: Any) -> Any:
    for value in values:
        if value is not None:
            return value
    return None


