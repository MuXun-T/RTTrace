def validate_scenario_contract_binding(
    config: WindowsFormalConfig,
    *,
    source_report_path: Path | None = None,
) -> None:
    if config.scenario_contract_path is None:
        return
    payload = scenario_contract_payload(config)
    input_contract = dict(payload.get("input_contract") or {})
    scenario_value = scenario_id(config)
    if scenario_value is None:
        raise ValueError(
            f"scenario contract missing scenario.scenario_id: {config.scenario_contract_path}"
        )
    trace_path_value = _first_nonempty_string(
        dict(payload.get("trace") or {}).get("path"),
        input_contract.get("trace_path"),
    )
    if trace_path_value is None:
        raise ValueError(
            f"scenario contract missing trace path binding: {config.scenario_contract_path}"
        )
    contract_trace_path = Path(trace_path_value).expanduser().resolve()
    if contract_trace_path != config.trace_path.resolve():
        raise ValueError(
            "scenario contract trace path mismatch: "
            f"contract={contract_trace_path} cli={config.trace_path.resolve()}"
        )
    trace_sha256 = _first_nonempty_string(
        dict(payload.get("trace") or {}).get("sha256"),
        input_contract.get("trace_sha256"),
    )
    if trace_sha256 is None:
        raise ValueError(
            f"scenario contract missing trace sha256 binding: {config.scenario_contract_path}"
        )
    if trace_sha256 != config.expected_trace_sha256:
        raise ValueError(
            "scenario contract trace sha256 mismatch: "
            f"contract={trace_sha256} cli={config.expected_trace_sha256}"
        )
    trace_size_raw = _first_present_value(
        dict(payload.get("trace") or {}).get("size_bytes"),
        input_contract.get("trace_size_bytes"),
    )
    if trace_size_raw is None:
        raise ValueError(
            f"scenario contract missing trace size binding: {config.scenario_contract_path}"
        )
    try:
        trace_size_bytes = int(trace_size_raw)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"scenario contract trace size must be an integer: {config.scenario_contract_path}"
        ) from exc
    if trace_size_bytes != config.expected_trace_size_bytes:
        raise ValueError(
            "scenario contract trace size mismatch: "
            f"contract={trace_size_bytes} cli={config.expected_trace_size_bytes}"
        )
    scheduler_strategy = scenario_scheduler_strategy(config)
    if scheduler_strategy is None:
        raise ValueError(
            f"scenario contract missing scheduler_strategy: {config.scenario_contract_path}"
        )
    if source_report_path is not None:
        contract_source_report_path = scenario_source_report_path(config)
        if contract_source_report_path is None:
            raise ValueError(
                f"scenario contract missing source_report_path binding: {config.scenario_contract_path}"
            )
        if contract_source_report_path != source_report_path.expanduser().resolve():
            raise ValueError(
                "scenario contract source report mismatch: "
                f"contract={contract_source_report_path} "
                f"cli={source_report_path.expanduser().resolve()}"
            )


