def build_config(args: argparse.Namespace) -> WindowsFormalConfig:
    repo_root = detect_repo_root()
    trace_path = args.trace.expanduser().resolve()
    archive_root = args.archive_root.expanduser().resolve()
    scratch_dir = None
    if getattr(args, "scratch_dir", None) is not None:
        scratch_dir = args.scratch_dir.expanduser().resolve()
    scenario_contract_path = None
    scenario_contract = None
    raw_scenario_contract = getattr(args, "scenario_contract", None)
    if raw_scenario_contract is not None:
        scenario_contract_path = raw_scenario_contract.expanduser().resolve()
        if not scenario_contract_path.exists() or not scenario_contract_path.is_file():
            raise FileNotFoundError(f"scenario contract not found: {scenario_contract_path}")
        loaded = json_load(scenario_contract_path)
        if not isinstance(loaded, dict):
            raise ValueError(f"scenario contract must be a JSON object: {scenario_contract_path}")
        scenario_contract = dict(loaded)
    config = WindowsFormalConfig(
        repo_root=repo_root,
        archive_root=archive_root,
        trace_path=trace_path,
        expected_trace_sha256=str(args.expected_trace_sha256),
        expected_trace_size_bytes=int(args.expected_trace_size_bytes),
        scratch_dir=scratch_dir,
        scenario_contract_path=scenario_contract_path,
        scenario_contract=scenario_contract,
    )
    validate_scenario_contract_binding(config)
    return config


def ensure_parent(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)


def json_load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def json_write(path: Path, payload: Any) -> None:
    ensure_parent(path)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")


def _resolve_group_relative_path(path_text: Any, *, group_root: Path) -> Path | None:
    if path_text is None:
        return None
    text = str(path_text).strip()
    if not text:
        return None
    path = Path(text).expanduser()
    if not path.is_absolute():
        path = (group_root / path).resolve()
    return path


def _proof_digest_candidate_paths(package_root: Path) -> list[Path]:
    candidates = (
        package_root / "control" / "proof_digest.json",
        package_root / "packages" / "run_001" / "control" / "proof_digest.json",
        package_root / "package" / "control" / "proof_digest.json",
        package_root / "proof_digest.json",
    )
    unique: list[Path] = []
    seen: set[str] = set()
    for candidate in candidates:
        candidate_key = str(candidate)
        if candidate_key in seen:
            continue
        seen.add(candidate_key)
        unique.append(candidate)
    return unique


def _row_package_roots(row: dict[str, Any], *, group_root: Path) -> list[Path]:
    roots: list[Path] = []
    seen: set[str] = set()
    artifact_refs = row.get("artifact_refs")
    candidate_values = (
        row.get("package_path"),
        artifact_refs.get("package_path") if isinstance(artifact_refs, dict) else None,
    )
    for value in candidate_values:
        resolved = _resolve_group_relative_path(value, group_root=group_root)
        if resolved is None:
            continue
        resolved_key = str(resolved)
        if resolved_key in seen:
            continue
        seen.add(resolved_key)
        roots.append(resolved)
    scenario_id = str(row.get("scenario_id") or "").strip()
    if scenario_id:
        conventional_root = (group_root / "packages" / scenario_id).resolve()
        conventional_key = str(conventional_root)
        if conventional_key not in seen:
            roots.append(conventional_root)
    return roots


def load_group_proof_digest(
    row: dict[str, Any],
    *,
    group_root: Path,
    error_label: str,
) -> dict[str, Any]:
    inline = row.get("proof_digest")
    if isinstance(inline, dict) and inline:
        return dict(inline)
    attempted_paths: list[str] = []
    seen_paths: set[str] = set()
    for package_root in _row_package_roots(row, group_root=group_root):
        for digest_path in _proof_digest_candidate_paths(package_root):
            digest_key = str(digest_path)
            if digest_key in seen_paths:
                continue
            seen_paths.add(digest_key)
            attempted_paths.append(digest_key)
            if digest_path.exists() and digest_path.is_file():
                payload = json_load(digest_path)
                if isinstance(payload, dict) and payload:
                    return dict(payload)
                raise RuntimeError(f"{error_label} proof_digest payload is not a JSON object: {digest_path}")
    scenario_id = str(row.get("scenario_id") or "").strip() or "<unknown>"
    attempted_suffix = f"; attempted={attempted_paths}" if attempted_paths else ""
    raise RuntimeError(
        f"{error_label} does not contain proof_digest rows for scenario_id={scenario_id}{attempted_suffix}"
    )


def checksum_file(path: Path) -> str:
    digest = sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_timestamp(path: Path) -> str:
    return datetime.fromtimestamp(path.stat().st_mtime).astimezone().isoformat()


def copy_file(src: Path, dst: Path) -> Path:
    ensure_parent(dst)
    shutil.copy2(src, dst)
    return dst


def copy_if_exists(src: Path, dst: Path) -> Path | None:
    if not src.exists():
        return None
    return copy_file(src, dst)


def copy_tree(src: Path, dst: Path) -> Path:
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    return dst


