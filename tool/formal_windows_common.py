    optional_dependency = str(scenario.get("optional_dependency") or "").strip()
    if advisor_mode == "openai_structured":
        advisor_config["llm_enabled"] = True
    elif advisor_mode == "offline_coefficients":
        if optional_dependency:
            advisor_config["optional_dependency"] = optional_dependency
        repo_candidate = config.repo_root / "tmp" / "runtime_optimization_formal_matrix" / "advisor_optional_sklearn_coefficients.json"
        archive_candidate = config.archive_root / "control" / "advisor_optional_sklearn_coefficients.json"
        coefficients_path = archive_candidate if archive_candidate.exists() else repo_candidate
        if not coefficients_path.exists():
            _write_default_offline_coefficients(coefficients_path)
        if coefficients_path.exists():
            advisor_config["coefficients_path"] = str(coefficients_path.resolve())
    return advisor_enabled, advisor_mode, advisor_config


